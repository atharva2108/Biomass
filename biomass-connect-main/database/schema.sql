-- =====================================================================
-- BIOMASS CONNECT — PostgreSQL schema (PostgreSQL 13 or newer)
-- ---------------------------------------------------------------------
-- Built only from the data the website stores today (js/common/store.js,
-- the profile pages, registration, admin pages, logistics page).
-- Every column maps to a field the frontend reads or writes; values the
-- frontend copies from another table (e.g. the biomass type on an order)
-- are read through the foreign key instead of being stored twice.
--
-- Run:   psql -U postgres -d biomass_connect -f database/schema.sql
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- Fixed value lists (same values the website uses)
-- ---------------------------------------------------------------------

CREATE TYPE user_role           AS ENUM ('farmer', 'manufacturer', 'powerplant', 'admin', 'logistics');
CREATE TYPE user_status         AS ENUM ('Pending', 'Active', 'Blocked', 'Rejected');
CREATE TYPE verification_status AS ENUM ('Pending', 'Approved', 'Rejected');
CREATE TYPE document_type       AS ENUM ('Aadhaar Card', 'GST Certificate');
CREATE TYPE listing_status      AS ENUM ('Active', 'Inactive', 'Sold Out');
CREATE TYPE order_status        AS ENUM ('Placed', 'Pickup Scheduled', 'In Transit', 'Delivered');
CREATE TYPE payment_status      AS ENUM ('Pending', 'Paid');
CREATE TYPE complaint_status    AS ENUM ('Open', 'Resolved');
CREATE TYPE notification_type   AS ENUM ('order', 'delivery', 'payment', 'alert');

-- ---------------------------------------------------------------------
-- 1. users — every account: farmer, manufacturer, power plant, admin,
--    logistics. Login is by email OR mobile, so both are unique.
-- ---------------------------------------------------------------------

CREATE TABLE users (
    user_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(100) NOT NULL,              -- person (farmer) or organisation name
    email                VARCHAR(100) NOT NULL UNIQUE CHECK (email = lower(email)),
    mobile               CHAR(10)     NOT NULL UNIQUE CHECK (mobile ~ '^[6-9][0-9]{9}$'),
    password_hash        VARCHAR(255) NOT NULL,
    role                 user_role    NOT NULL,
    status               user_status  NOT NULL DEFAULT 'Pending',
    security_question    VARCHAR(100) NOT NULL,
    security_answer_hash VARCHAR(255) NOT NULL,
    registered_on        DATE         NOT NULL DEFAULT CURRENT_DATE,
    previous_status      user_status,                        -- restored when admin unblocks
    block_category       VARCHAR(50),
    block_reason         VARCHAR(500),
    blocked_on           DATE,
    CHECK (status <> 'Blocked' OR (block_category IS NOT NULL AND block_reason IS NOT NULL AND blocked_on IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- 2–4. Role profiles (one row per user of that role; PK = FK)
-- ---------------------------------------------------------------------

CREATE TABLE farmer_profiles (
    user_id         BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    dob             DATE,
    gender          VARCHAR(10)  CHECK (gender IN ('Male', 'Female', 'Other')),
    address         VARCHAR(200),
    village         VARCHAR(60),
    district        VARCHAR(50),
    state           VARCHAR(60)  NOT NULL,
    pincode         CHAR(6)      NOT NULL CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    farm_area_acres NUMERIC(8,2) CHECK (farm_area_acres > 0 AND farm_area_acres <= 1000),
    primary_crops   VARCHAR(100),
    account_holder  VARCHAR(100),
    bank_name       VARCHAR(100),
    account_no      VARCHAR(18)  CHECK (account_no ~ '^[0-9]{9,18}$'),
    ifsc            CHAR(11)     CHECK (ifsc ~ '^[A-Z]{4}0[A-Z0-9]{6}$'),
    upi_id          VARCHAR(100),
    aadhaar_last4   CHAR(4)      NOT NULL CHECK (aadhaar_last4 ~ '^[0-9]{4}$'),
    pan             CHAR(10)     CHECK (pan ~ '^[A-Z]{5}[0-9]{4}[A-Z]$'),
    photo_url       VARCHAR(255),
    updated_at      DATE
);

CREATE TABLE manufacturer_profiles (
    user_id               BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    contact_person        VARCHAR(100) NOT NULL,
    gstin                 CHAR(15)     NOT NULL UNIQUE CHECK (gstin ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$'),
    address               VARCHAR(200),
    city                  VARCHAR(60),
    state                 VARCHAR(60)  NOT NULL,
    pincode               CHAR(6)      NOT NULL CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    capacity_tons_per_day NUMERIC(8,2) CHECK (capacity_tons_per_day > 0 AND capacity_tons_per_day <= 5000),
    photo_url             VARCHAR(255),
    updated_at            DATE
);

CREATE TABLE powerplant_profiles (
    user_id        BIGINT PRIMARY KEY REFERENCES users (user_id) ON DELETE CASCADE,
    contact_person VARCHAR(100) NOT NULL,
    designation    VARCHAR(60),
    gstin          CHAR(15)     NOT NULL UNIQUE CHECK (gstin ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$'),
    capacity_mw    NUMERIC(8,2) CHECK (capacity_mw > 0 AND capacity_mw <= 10000),
    address        VARCHAR(200),
    city           VARCHAR(60),
    state          VARCHAR(60)  NOT NULL,
    pincode        CHAR(6)      NOT NULL CHECK (pincode ~ '^[1-9][0-9]{5}$'),
    photo_url      VARCHAR(255),
    updated_at     DATE
);

-- ---------------------------------------------------------------------
-- 5. verification_documents — the ONE document uploaded at registration
--    (Aadhaar card for farmers, GST certificate for the others),
--    approved or rejected by admin.
-- ---------------------------------------------------------------------

CREATE TABLE verification_documents (
    document_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL UNIQUE REFERENCES users (user_id) ON DELETE CASCADE,
    doc_type        document_type       NOT NULL,
    doc_number      VARCHAR(30)         NOT NULL,          -- Aadhaar number (masked) or GSTIN
    doc_file        VARCHAR(255)        NOT NULL,          -- stored file path / URL
    doc_size_kb     INTEGER             CHECK (doc_size_kb > 0 AND doc_size_kb <= 5120),
    submitted_on    DATE                NOT NULL DEFAULT CURRENT_DATE,
    status          verification_status NOT NULL DEFAULT 'Pending',
    reviewed_by     BIGINT REFERENCES users (user_id),     -- admin
    reviewed_on     DATE,
    reason_category VARCHAR(50),
    reason          VARCHAR(500),
    CHECK (status = 'Pending' OR (reviewed_by IS NOT NULL AND reviewed_on IS NOT NULL)),
    CHECK (status <> 'Rejected' OR (reason_category IS NOT NULL AND reason IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- 6. biomass_listings — created by farmers, bought whole by manufacturers
-- ---------------------------------------------------------------------

CREATE TABLE biomass_listings (
    listing_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id      BIGINT NOT NULL REFERENCES users (user_id),
    biomass_type   VARCHAR(50)    NOT NULL,
    quantity_tons  NUMERIC(10,2)  NOT NULL CHECK (quantity_tons > 0 AND quantity_tons <= 10000),
    price_per_ton  NUMERIC(10,2)  NOT NULL CHECK (price_per_ton >= 100 AND price_per_ton <= 100000),
    location       VARCHAR(100)   NOT NULL,                -- village / pickup point
    district       VARCHAR(50)    NOT NULL,
    state          VARCHAR(60)    NOT NULL,
    available_from DATE           NOT NULL,
    description    VARCHAR(500),
    status         listing_status NOT NULL DEFAULT 'Active',
    created_at     DATE           NOT NULL DEFAULT CURRENT_DATE
);

-- ---------------------------------------------------------------------
-- 7. pellet_listings — created by manufacturers, bought whole by power
--    plants. The quality spec is what batch feedback is scored against.
-- ---------------------------------------------------------------------

CREATE TABLE pellet_listings (
    listing_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacturer_id BIGINT NOT NULL REFERENCES users (user_id),
    pellet_type     VARCHAR(50)    NOT NULL,
    grade           VARCHAR(20)    NOT NULL CHECK (grade IN ('Premium', 'Standard', 'Industrial')),
    quantity_tons   NUMERIC(10,2)  NOT NULL CHECK (quantity_tons > 0 AND quantity_tons <= 10000),
    price_per_ton   NUMERIC(10,2)  NOT NULL CHECK (price_per_ton >= 1000 AND price_per_ton <= 50000),
    diameter_mm     NUMERIC(4,1)   NOT NULL CHECK (diameter_mm BETWEEN 6 AND 12),
    length_mm       NUMERIC(4,1)   NOT NULL CHECK (length_mm BETWEEN 10 AND 50),
    moisture_pct    NUMERIC(5,2)   NOT NULL CHECK (moisture_pct BETWEEN 0 AND 15),
    ash_content_pct NUMERIC(5,2)   NOT NULL CHECK (ash_content_pct BETWEEN 0 AND 20),
    calorific_value INTEGER        NOT NULL CHECK (calorific_value BETWEEN 3000 AND 5500),   -- kcal/kg
    bulk_density    INTEGER        NOT NULL CHECK (bulk_density BETWEEN 500 AND 800),        -- kg/m³
    pickup_location VARCHAR(100)   NOT NULL,
    available_from  DATE           NOT NULL,
    certification   VARCHAR(60),
    status          listing_status NOT NULL DEFAULT 'Active',
    created_at      DATE           NOT NULL DEFAULT CURRENT_DATE
);

-- ---------------------------------------------------------------------
-- 8. purchase_orders — a manufacturer buys a WHOLE biomass listing.
--    Never accepted / rejected / cancelled. Logistics columns are filled
--    only by the logistics team; payment by the buyer after delivery.
-- ---------------------------------------------------------------------

CREATE TABLE purchase_orders (
    order_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id        BIGINT NOT NULL UNIQUE REFERENCES biomass_listings (listing_id),
    farmer_id         BIGINT NOT NULL REFERENCES users (user_id),        -- seller (owner of the listing)
    manufacturer_id   BIGINT NOT NULL REFERENCES users (user_id),        -- buyer
    quantity_tons     NUMERIC(10,2) NOT NULL CHECK (quantity_tons > 0),  -- copied from the listing at purchase
    price_per_ton     NUMERIC(10,2) NOT NULL CHECK (price_per_ton > 0),
    total_amount      NUMERIC(12,2) GENERATED ALWAYS AS (quantity_tons * price_per_ton) STORED,
    order_date        DATE          NOT NULL DEFAULT CURRENT_DATE,
    pickup_address    VARCHAR(200)  NOT NULL,
    delivery_address  VARCHAR(200)  NOT NULL,
    notes             VARCHAR(500),
    status            order_status  NOT NULL DEFAULT 'Placed',
    -- logistics (entered only by the logistics team)
    pickup_date       DATE,
    expected_delivery DATE,
    vehicle_no        VARCHAR(13)   CHECK (vehicle_no ~ '^[A-Z]{2}[ -]?[0-9]{1,2}[ -]?[A-Z]{0,3}[ -]?[0-9]{4}$'),
    driver_name       VARCHAR(60),
    driver_mobile     CHAR(10)      CHECK (driver_mobile ~ '^[6-9][0-9]{9}$'),
    dispatched_date   DATE,
    delivered_date    DATE,
    -- payment (buyer marks paid after delivery)
    payment_status    payment_status NOT NULL DEFAULT 'Pending',
    paid_on           DATE,
    CHECK (farmer_id <> manufacturer_id),
    CHECK (expected_delivery >= pickup_date),
    CHECK (status = 'Placed' OR (pickup_date IS NOT NULL AND expected_delivery IS NOT NULL
                                 AND vehicle_no IS NOT NULL AND driver_name IS NOT NULL AND driver_mobile IS NOT NULL)),
    CHECK (status NOT IN ('In Transit', 'Delivered') OR dispatched_date IS NOT NULL),
    CHECK (status <> 'Delivered' OR delivered_date IS NOT NULL),
    CHECK (payment_status = 'Pending' OR (paid_on IS NOT NULL AND status = 'Delivered'))
);

-- ---------------------------------------------------------------------
-- 9. pellet_orders — a power plant buys a WHOLE pellet listing.
--    Same lifecycle, logistics and payment columns as purchase_orders.
-- ---------------------------------------------------------------------

CREATE TABLE pellet_orders (
    order_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id        BIGINT NOT NULL UNIQUE REFERENCES pellet_listings (listing_id),
    manufacturer_id   BIGINT NOT NULL REFERENCES users (user_id),        -- seller (owner of the listing)
    powerplant_id     BIGINT NOT NULL REFERENCES users (user_id),        -- buyer
    quantity_tons     NUMERIC(10,2) NOT NULL CHECK (quantity_tons > 0),
    price_per_ton     NUMERIC(10,2) NOT NULL CHECK (price_per_ton > 0),
    total_amount      NUMERIC(12,2) GENERATED ALWAYS AS (quantity_tons * price_per_ton) STORED,
    order_date        DATE          NOT NULL DEFAULT CURRENT_DATE,
    pickup_address    VARCHAR(200)  NOT NULL,
    delivery_address  VARCHAR(200)  NOT NULL,
    notes             VARCHAR(500),
    status            order_status  NOT NULL DEFAULT 'Placed',
    pickup_date       DATE,
    expected_delivery DATE,
    vehicle_no        VARCHAR(13)   CHECK (vehicle_no ~ '^[A-Z]{2}[ -]?[0-9]{1,2}[ -]?[A-Z]{0,3}[ -]?[0-9]{4}$'),
    driver_name       VARCHAR(60),
    driver_mobile     CHAR(10)      CHECK (driver_mobile ~ '^[6-9][0-9]{9}$'),
    dispatched_date   DATE,
    delivered_date    DATE,
    payment_status    payment_status NOT NULL DEFAULT 'Pending',
    paid_on           DATE,
    CHECK (manufacturer_id <> powerplant_id),
    CHECK (expected_delivery >= pickup_date),
    CHECK (status = 'Placed' OR (pickup_date IS NOT NULL AND expected_delivery IS NOT NULL
                                 AND vehicle_no IS NOT NULL AND driver_name IS NOT NULL AND driver_mobile IS NOT NULL)),
    CHECK (status NOT IN ('In Transit', 'Delivered') OR dispatched_date IS NOT NULL),
    CHECK (status <> 'Delivered' OR delivered_date IS NOT NULL),
    CHECK (payment_status = 'Pending' OR (paid_on IS NOT NULL AND status = 'Delivered'))
);

-- ---------------------------------------------------------------------
-- 10. pellet_feedback — batch details a power plant enters after a
--     pellet delivery; one per order. score (1–5) is computed by the API
--     against the listing's spec; the manufacturer rating = AVG(score).
-- ---------------------------------------------------------------------

CREATE TABLE pellet_feedback (
    feedback_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          BIGINT NOT NULL UNIQUE REFERENCES pellet_orders (order_id),
    received_date     DATE          NOT NULL,
    quantity_received NUMERIC(10,2) NOT NULL CHECK (quantity_received > 0),
    moisture_pct      NUMERIC(5,2)  NOT NULL CHECK (moisture_pct BETWEEN 0 AND 40),
    ash_content_pct   NUMERIC(5,2)  NOT NULL CHECK (ash_content_pct BETWEEN 0 AND 40),
    calorific_value   INTEGER       NOT NULL CHECK (calorific_value BETWEEN 1000 AND 6000),
    score             NUMERIC(2,1)  NOT NULL CHECK (score BETWEEN 1 AND 5),
    remarks           VARCHAR(300)
);

-- ---------------------------------------------------------------------
-- 11. complaints — raised on ONE order (biomass or pellet) by its buyer
--     or seller; admin can only view and resolve.
-- ---------------------------------------------------------------------

CREATE TABLE complaints (
    complaint_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raised_by         BIGINT NOT NULL REFERENCES users (user_id),
    against_user_id   BIGINT NOT NULL REFERENCES users (user_id),
    purchase_order_id BIGINT REFERENCES purchase_orders (order_id),
    pellet_order_id   BIGINT REFERENCES pellet_orders (order_id),
    category          VARCHAR(50)      NOT NULL,
    description       VARCHAR(500)     NOT NULL,
    status            complaint_status NOT NULL DEFAULT 'Open',
    raised_on         DATE             NOT NULL DEFAULT CURRENT_DATE,
    resolution        VARCHAR(500),
    resolved_on       DATE,
    CHECK (num_nonnulls(purchase_order_id, pellet_order_id) = 1),     -- exactly one order
    CHECK (raised_by <> against_user_id),
    CHECK (status = 'Open' OR (resolution IS NOT NULL AND resolved_on IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- 12. certificates — Government Norms Compliance Certificate issued by
--     admin to a power plant.
-- ---------------------------------------------------------------------

CREATE TABLE certificates (
    certificate_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_no VARCHAR(30)  NOT NULL UNIQUE,              -- e.g. BC/GN/2026/1001
    powerplant_id  BIGINT       NOT NULL REFERENCES users (user_id),
    title          VARCHAR(100) NOT NULL DEFAULT 'Government Norms Compliance Certificate',
    issue_date     DATE         NOT NULL,
    valid_until    DATE         NOT NULL,
    remarks        VARCHAR(200),
    issued_by      BIGINT       NOT NULL REFERENCES users (user_id),   -- admin
    CHECK (valid_until > issue_date)
);

-- ---------------------------------------------------------------------
-- 13. consumption_logs — daily pellet / coal use per unit of a plant
--     (Biomass Consumption page; Carbon Savings is calculated from it).
-- ---------------------------------------------------------------------

CREATE TABLE consumption_logs (
    entry_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    powerplant_id      BIGINT        NOT NULL REFERENCES users (user_id),
    entry_date         DATE          NOT NULL,
    unit               VARCHAR(30)   NOT NULL,                -- e.g. 'Unit 3 (210 MW)'
    pellets_tons       NUMERIC(10,2) NOT NULL CHECK (pellets_tons > 0 AND pellets_tons <= 10000),
    coal_tons          NUMERIC(10,2) NOT NULL CHECK (coal_tons > 0 AND coal_tons <= 50000),
    cofiring_ratio_pct NUMERIC(5,2)  GENERATED ALWAYS AS (round(pellets_tons * 100 / (pellets_tons + coal_tons), 2)) STORED,
    energy_mwh         NUMERIC(10,2) NOT NULL CHECK (energy_mwh > 0 AND energy_mwh <= 100000),
    remarks            VARCHAR(200),
    UNIQUE (powerplant_id, entry_date, unit)                  -- one entry per unit per day
);

-- ---------------------------------------------------------------------
-- 14. notifications — the bell / Notifications page of each user
-- ---------------------------------------------------------------------

CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT            NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    type            notification_type NOT NULL,
    title           VARCHAR(100)      NOT NULL,
    message         VARCHAR(300)      NOT NULL,
    link            VARCHAR(200),
    is_read         BOOLEAN           NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ       NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 15. audit_logs — every admin action (Audit & Compliance page)
-- ---------------------------------------------------------------------

CREATE TABLE audit_logs (
    log_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT       NOT NULL REFERENCES users (user_id),
    action    VARCHAR(200) NOT NULL,
    module    VARCHAR(50)  NOT NULL,                          -- Users, Verification, Disputes, Compliance, Settings
    logged_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- 16. platform_settings — admin Settings page (always exactly one row)
-- ---------------------------------------------------------------------

CREATE TABLE platform_settings (
    settings_id           SMALLINT PRIMARY KEY DEFAULT 1 CHECK (settings_id = 1),
    platform_name         VARCHAR(60)   NOT NULL DEFAULT 'Biomass Connect',
    support_email         VARCHAR(100)  NOT NULL DEFAULT 'support@biomassconnect.in',
    support_phone         CHAR(10)      NOT NULL DEFAULT '9876543210' CHECK (support_phone ~ '^[6-9][0-9]{9}$'),
    commission_pct        NUMERIC(5,2)  NOT NULL DEFAULT 2.5    CHECK (commission_pct BETWEEN 0 AND 20),
    gst_on_commission_pct NUMERIC(5,2)  NOT NULL DEFAULT 18     CHECK (gst_on_commission_pct BETWEEN 0 AND 28),
    min_order_tons        INTEGER       NOT NULL DEFAULT 5      CHECK (min_order_tons BETWEEN 1 AND 1000),
    session_timeout_min   INTEGER       NOT NULL DEFAULT 30     CHECK (session_timeout_min BETWEEN 5 AND 240),
    max_login_attempts    INTEGER       NOT NULL DEFAULT 5      CHECK (max_login_attempts BETWEEN 3 AND 10),
    max_upload_mb         INTEGER       NOT NULL DEFAULT 5      CHECK (max_upload_mb BETWEEN 1 AND 25),
    notify_registrations  BOOLEAN       NOT NULL DEFAULT TRUE,
    notify_complaints     BOOLEAN       NOT NULL DEFAULT TRUE,
    notify_high_value     BOOLEAN       NOT NULL DEFAULT TRUE,
    high_value_threshold  NUMERIC(12,2) NOT NULL DEFAULT 1000000 CHECK (high_value_threshold BETWEEN 10000 AND 100000000)

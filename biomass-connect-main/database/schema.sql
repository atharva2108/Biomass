-- ---------------------------------------------------------------------

CREATE INDEX idx_biomass_listings_farmer   ON biomass_listings (farmer_id);
CREATE INDEX idx_biomass_listings_status   ON biomass_listings (status);
CREATE INDEX idx_pellet_listings_maker     ON pellet_listings (manufacturer_id);
CREATE INDEX idx_pellet_listings_status    ON pellet_listings (status);
CREATE INDEX idx_purchase_orders_farmer    ON purchase_orders (farmer_id);
CREATE INDEX idx_purchase_orders_buyer     ON purchase_orders (manufacturer_id);
CREATE INDEX idx_purchase_orders_status    ON purchase_orders (status);
CREATE INDEX idx_pellet_orders_maker       ON pellet_orders (manufacturer_id);
CREATE INDEX idx_pellet_orders_buyer       ON pellet_orders (powerplant_id);
CREATE INDEX idx_pellet_orders_status      ON pellet_orders (status);
CREATE INDEX idx_complaints_raised_by      ON complaints (raised_by);
CREATE INDEX idx_complaints_against        ON complaints (against_user_id);
CREATE INDEX idx_complaints_purchase_order ON complaints (purchase_order_id);
CREATE INDEX idx_complaints_pellet_order   ON complaints (pellet_order_id);

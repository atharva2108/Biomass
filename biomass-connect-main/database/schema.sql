CREATE INDEX idx_notifications_user        ON notifications (user_id, is_read);
CREATE INDEX idx_audit_logs_time           ON audit_logs (logged_at);

-- ---------------------------------------------------------------------
-- Manufacturer rating (computed, never stored): average batch score
-- ---------------------------------------------------------------------

CREATE VIEW manufacturer_ratings AS
SELECT po.manufacturer_id,
       round(avg(f.score), 1) AS rating,
       count(*)               AS batches
FROM pellet_feedback f
JOIN pellet_orders po ON po.order_id = f.order_id
GROUP BY po.manufacturer_id;

COMMIT;

-- ---------------------------------------------------------------------
-- Rules the API must check (they need data from other tables):
--  * purchase_orders.farmer_id = biomass_listings.farmer_id of listing_id;
--    pellet_orders.manufacturer_id = pellet_listings.manufacturer_id.
--  * Placing an order copies quantity and price from the listing and sets
--    the listing to 'Sold Out' in the same transaction; only 'Active'
--    listings can be bought; 'Sold Out' listings cannot be edited.
--  * Each *_id column holds a user of the right role (farmer_id → farmer,
--    powerplant_id → powerplant, reviewed_by / issued_by → admin, …).
--  * Only logistics users change order status and logistics columns;
--    only the buyer sets payment_status = 'Paid'.
--  * pellet_feedback only for a 'Delivered' pellet order, received_date
--    on or after delivered_date, quantity_received <= order quantity.
--  * complaints.raised_by must be the buyer or seller of that order.
-- ---------------------------------------------------------------------
